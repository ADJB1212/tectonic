#include "dpx-pdfdev.h"
#include "tectonic-pipeline.h"

const size_t *tt_pdf_renderer_abi_layout(size_t *length) {
    static const size_t layout[] = {
        sizeof(int),
        _Alignof(int),
        sizeof(int32_t),
        _Alignof(int32_t),
        sizeof(size_t),
        _Alignof(size_t),
        sizeof(double),
        _Alignof(double),
        ((char)-1 < 0),
        sizeof(pdf_tmatrix),
        _Alignof(pdf_tmatrix),
        offsetof(pdf_tmatrix, a),
        offsetof(pdf_tmatrix, b),
        offsetof(pdf_tmatrix, c),
        offsetof(pdf_tmatrix, d),
        offsetof(pdf_tmatrix, e),
        offsetof(pdf_tmatrix, f),
        sizeof(pdf_rect),
        _Alignof(pdf_rect),
        offsetof(pdf_rect, llx),
        offsetof(pdf_rect, lly),
        offsetof(pdf_rect, urx),
        offsetof(pdf_rect, ury),
        sizeof(pdf_coord),
        _Alignof(pdf_coord),
        offsetof(pdf_coord, x),
        offsetof(pdf_coord, y),
        sizeof(transform_info),
        _Alignof(transform_info),
        offsetof(transform_info, width),
        offsetof(transform_info, height),
        offsetof(transform_info, depth),
        offsetof(transform_info, matrix),
        offsetof(transform_info, bbox),
        offsetof(transform_info, flags),
        sizeof(tt_pdf_render_font),
        _Alignof(tt_pdf_render_font),
        offsetof(tt_pdf_render_font, name),
        offsetof(tt_pdf_render_font, size),
        offsetof(tt_pdf_render_font, format),
        offsetof(tt_pdf_render_font, wmode),
        offsetof(tt_pdf_render_font, extend),
        offsetof(tt_pdf_render_font, slant),
        offsetof(tt_pdf_render_font, bold),
        sizeof(tt_pdf_render_command),
        _Alignof(tt_pdf_render_command),
        offsetof(tt_pdf_render_command, kind),
        offsetof(tt_pdf_render_command, font),
        offsetof(tt_pdf_render_command, x),
        offsetof(tt_pdf_render_command, y),
        offsetof(tt_pdf_render_command, width),
        offsetof(tt_pdf_render_command, height),
        offsetof(tt_pdf_render_command, data),
        offsetof(tt_pdf_render_command, length)
    };
    *length = sizeof(layout) / sizeof(layout[0]);
    return layout;
}
